#!/usr/bin/env python3
"""Generate hermes/skills/core-practices/SKILL.md from standards/rules.json.

python3 hermes/build_skills.py          # write the skill
python3 hermes/build_skills.py --check  # exit 1 when the committed skill is stale
python3 hermes/build_skills.py --self-test
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "standards" / "rules.json"
OUT = ROOT / "hermes" / "skills" / "core-practices" / "SKILL.md"

HEAD = """---
name: core-practices
description: "Use when building, fixing or reviewing anything. The shared core rules by doc and stack."
---

# Core practices (generated, do not edit)

Generated by `hermes/build_skills.py` from `standards/rules.json`. Change the docs or the registry in
the core repo, never this file. The full docs sit next to this skill in `references/` after a sync.

How to use it:

1. Before a build, fix or review, read the rules for the stacks you touch (the `applies_to` column)
   plus every `all` rule. A `must` rule is mandatory. A `should` rule is the default; deviate only
   with a stated reason.
2. Where the work breaks a rule, fix the work. Where the rule cannot hold for a good reason, record an
   explicit exception in the consumer overlay, never a silent deviation.
3. When the work finds a pattern another consumer's agent would want, knowing nothing about this
   machine, and it carries no name, path or value of this estate, add it to this account's
   `consumer-report` issue on the core (CONTRIBUTING.md "Does it belong in the core?"). Anything that
   fails that test stays local.

"""


def render_rules(rules: list) -> str:
    by_doc: dict[str, list] = {}
    for r in rules:
        by_doc.setdefault(r["ref"].split()[0], []).append(r)
    out = [HEAD]
    for doc in sorted(by_doc):
        out.append(f"## {doc}\n\n")
        out.append("| Rule | Level | Applies to | Check | Statement |\n|---|---|---|---|---|\n")
        for r in by_doc[doc]:
            stmt = " ".join(str(r.get("statement", "")).split()).replace("|", "/")
            stacks = ", ".join(r.get("applies_to") or ["all"])
            kind = (r.get("check") or {}).get("kind", "")
            level = r.get("level") or "must"
            out.append(
                f"| `{r['id']}` {r.get('title', '')} | {level} | {stacks} | {kind} | {stmt} |\n"
            )
        out.append("\n")
    return "".join(out).rstrip("\n") + "\n"


def render() -> str:
    data = json.loads(RULES.read_text())
    return render_rules(data["rules"] if isinstance(data, dict) else data)


def self_test() -> int:
    rules = [
        {"id": "a-1", "ref": "DOC 1", "title": "T", "statement": "S", "level": "should"},
        {"id": "a-2", "ref": "DOC 2", "title": "U", "statement": "V", "level": "must"},
    ]
    rows = {ln.split("`")[1]: ln for ln in render_rules(rules).splitlines() if ln.startswith("| `")}
    ok = "| should |" in rows["a-1"] and "| must |" in rows["a-2"]
    levels = {r["id"]: r["level"] for r in json.loads(RULES.read_text())["rules"]}
    text = render()
    for rid, lvl in levels.items():
        if f"| `{rid}` " not in text or f"| {lvl} |" not in next(
            ln for ln in text.splitlines() if ln.startswith(f"| `{rid}` ")
        ):
            ok = False
            print(f"level lost for {rid}")
    print("build_skills self-test " + ("ok" if ok else "FAILED"))
    return 0 if ok else 1


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        return self_test()
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale. Run: python3 hermes/build_skills.py")
            return 1
        print("core-practices is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
